#!/usr/bin/env bash
# make-preview.sh — refresh the preview/with-addons branch (display-only):
# current dev/gridguard + current local notebook under addons/, assembled as
# one tree and pushed to staging. This is the REF YOU PREPARE A GITHUB PUSH
# FROM: merge it into main when you decide to announce the addon.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
BR="${1:-dev/gridguard}"
NB="addons/gridguard"
git -C "$NB" rev-parse --git-dir >/dev/null || { echo "no notebook at $NB"; exit 1; }
git diff --quiet && git diff --cached --quiet || { echo "parent has uncommitted changes — commit first"; exit 1; }
git -C "$NB" diff --quiet && git -C "$NB" diff --cached --quiet || { echo "notebook dirty — commit first"; exit 1; }
[ -z "$(git ls-tree --name-only "$BR" -- addons)" ] || { echo "BRANCH $BR already tracks addons/ — nothing to assemble"; exit 1; }
# Object bridge: preview commits reference the notebook's tree objects, so
# the parent's OWN store must hold them too — later log/merge operations on
# the preview ref (the squash into main!) read them from here, not via the
# alternates below (observed 2026-11-04: "unable to read tree"). Fast-forward
# only by construction: a rewritten notebook history rejects loudly instead
# of forcing.
git fetch "$NB" "refs/heads/main:refs/heads/addon-history"
NBTREE="$(git -C "$NB" rev-parse 'HEAD^{tree}')"
TMPIDX="$(mktemp)"; trap 'rm -f "$TMPIDX"' EXIT
export GIT_INDEX_FILE="$TMPIDX"
# the notebook keeps its own object store — let the parent's plumbing read it
# directly (fix2026-11-03: read-tree --prefix failed once the notebook moved
# past the parked addon-history ref)
export GIT_ALTERNATE_OBJECT_DIRECTORIES="$(git -C "$NB" rev-parse --absolute-git-dir)/objects"
git read-tree "$BR"
git read-tree --prefix="$NB/" "$NBTREE"
TREE="$(git write-tree)"; unset GIT_INDEX_FILE
NB_SHA="$(git -C "$NB" rev-parse HEAD)"
COMMIT="$(git commit-tree "$TREE" -p "$BR" -m "preview/with-addons: $BR @ $(git rev-parse --short "$BR") + notebook @ $(git -C "$NB" rev-parse --short HEAD) (generated by make-preview.sh)")"
# generated ref: every refresh is a sibling assembly on top of $BR, so the
# previous generated tip is never an ancestor — force is the designed update
# (owner 2026-11-03: "the staging repo can be deleted, it is staging")
git push --force staging "$COMMIT:refs/heads/preview/with-addons"
echo "OK preview/with-addons -> ${COMMIT}"
